'use strict'

/**
 * 幂等时间窗（纯函数，无 IO，可单测）。
 *
 * ── 为什么需要时间窗 ────────────────────────────────────────
 * 幂等键若只看「业务参数 + 终态」，会永久挡住用户的合法二次提交：
 * 用户 10 分钟后想以同样参数再挂一单，同样参数的在途单还在，键依然命中，
 * 于是新意图被静默吞掉——这是比「重复点击多建一单」更难排查的故障。
 * 加时间窗后：窗内 = 判定为重试（拦），窗外 = 判定为新意图（放行）。
 *
 * ── 窗口取值依据 ────────────────────────────────────────────
 * 上界必须覆盖「一次用户意图从发起到可感知完成」的时长，
 * 否则用户看到失败/超时后手动重试会被自己的第一次请求拦下——
 * 这比漏拦重复点击更糟（用户会以为系统坏了）。
 *   · 网络重试：客户端退避重试典型 3 次，累计 1s/3s/9s，约 15s
 *   · 弱网跨境：单请求往返可达 5~10s，首次+重试累计约 30s
 *   · 用户手动重试：看清报错再点，通常 > 5s
 * 取 60s 覆盖上述全部场景并留一倍余量。
 *
 * 下界必须短于「用户完成一次思考并改变参数」的时长，
 * 否则改价重试会被误拦。改价后 price 变化即换键，本身不受影响。
 *
 * 各接口取值不同的理由见下方常量注释。
 */

/** 求购/委托单：60s。前端无二次确认弹窗，重复点击与网络重试均在 30s 内完成 */
const ENTRUST_WINDOW_SEC = 60

/**
 * 开盒：60s。
 * 开盒的语义天然是「消耗型」（count-1），用户连点两次的第二次
 * 几乎必然是误触或重试（开盒结果需看完动画才会再点）。
 */
const OPENBOX_WINDOW_SEC = 60

/**
 * sell（寄售）：**不用时间窗**。
 * 幂等键是「该藏品已存在寄售中的挂单」，挂单终结（售出/下架）后键自然失效。
 * 加时间窗会出现漏洞：挂单在窗内被买家买走→ 藏品回到可售状态 →
 * 用户重新挂单时若距上次提交超过窗口，会漏拦并新建，
 * 或在窗口内被旧挂单的残留记录误拦。终态条件已足够精确。
 */

/** 当前 unix 秒 */
function nowSec() {
  return Math.floor(Date.now() / 1000)
}

/**
 * 时间窗下界。
 * @param {number} windowSec 窗口长度（秒）
 * @param {number} [now] 当前时间戳，便于测试注入
 * @returns {number} unix 秒
 */
function since(windowSec, now) {
  return (now === undefined ? nowSec() : now) - windowSec
}

module.exports = { ENTRUST_WINDOW_SEC, OPENBOX_WINDOW_SEC, nowSec, since }